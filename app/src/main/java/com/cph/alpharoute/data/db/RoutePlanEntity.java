package com.cph.alpharoute.data.db;

import androidx.annotation.NonNull;
import androidx.room.ColumnInfo;
import androidx.room.Entity;
import androidx.room.ForeignKey;
import androidx.room.Index;
import androidx.room.PrimaryKey;

/**
 * A saved route plan (Version 18).
 *
 * <p><b>Why this table exists.</b> The optimiser is a solver, and a solver given the same problem can
 * return a different order - a different road closure, a slightly different matrix, a service that has
 * been retrained. So "the plan" was not a thing the app could promise: it was whatever the last request
 * happened to return.
 *
 * <p>A saved plan is a decision the user made and the app keeps. Recalculating is still available; it is
 * just no longer the only thing that can happen.
 *
 * <h3>What it stores</h3>
 *
 * <pre>
 *   name         "Plan 1" by default, or whatever the user typed
 *   roundNumber  which round it was made for, so a plan from round 1 is not silently applied to round 2
 *   createdAt    when it was saved
 *   totals       the distance and duration the solver reported, kept for display
 * </pre>
 *
 * <p>The stops live in {@link RoutePlanStopEntity}, not in a column here. A plan is a list of places in an
 * order, and an order is a relationship - storing it as a delimited string would make it unqueryable and
 * would put the parsing burden on every reader.
 */
@Entity(
        tableName = "route_plans",
        indices = {
                @Index(value = "roundNumber"),
                @Index(value = "createdAt")
        }
)
public class RoutePlanEntity {

    @PrimaryKey(autoGenerate = true)
    public long id;

    /**
     * What the user called it.
     *
     * <p>Never blank - a plan with no name cannot be chosen from a list. The default is generated by the
     * repository ("Plan 1", "Plan 2"…) rather than left to the UI, so two plans cannot end up with the
     * same default name.
     */
    @NonNull
    @ColumnInfo(name = "name")
    public String name = "";

    /** Which round this plan was made for. */
    @ColumnInfo(name = "roundNumber")
    public int roundNumber = 1;

    /** When it was saved, epoch millis. */
    @ColumnInfo(name = "createdAt")
    public long createdAt;

    /** The total driving distance the solver reported, in metres. */
    @ColumnInfo(name = "totalDistanceMetres")
    public double totalDistanceMetres;

    /** The total driving time the solver reported, in seconds. */
    @ColumnInfo(name = "totalDurationSeconds")
    public long totalDurationSeconds;

    /** Whether the plan started at the user's position when it was made. */
    @ColumnInfo(name = "startedAtLocation", defaultValue = "0")
    public boolean startedAtLocation;

    /** Whether the plan finished at Home when it was made. */
    @ColumnInfo(name = "endedAtHome", defaultValue = "0")
    public boolean endedAtHome;
}
