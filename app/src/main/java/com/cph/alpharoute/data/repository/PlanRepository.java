package com.cph.alpharoute.data.repository;

import android.util.Log;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.lifecycle.LiveData;

import com.cph.alpharoute.data.db.RoutePlanDao;
import com.cph.alpharoute.data.db.RoutePlanEntity;
import com.cph.alpharoute.data.db.RoutePlanStopEntity;
import com.cph.alpharoute.domain.OptimizationPlan;
import com.cph.alpharoute.domain.OptimizationStop;
import com.cph.alpharoute.util.AppExecutors;

import java.util.ArrayList;
import java.util.List;

/**
 * The saved route plans - the order the user decided, kept.
 *
 * <p><b>Why this exists at all.</b> A planner is a solver, and a solver asked the same question twice can
 * answer differently. So "the plan" was never a thing the app could promise; it was whatever the last
 * calculation happened to return. A saved plan is a decision the user made, and the app keeps it.
 *
 * <p><b>The user's order is data, not a preference.</b> It is written to the same database as the stores
 * and the completion history, with the same rules: every write goes through {@code diskIO()} - a single
 * thread - and commits locally before anything else happens. Nothing in this class touches the network.
 *
 * <p><b>A plan is only ever written whole.</b> {@link RoutePlanDao#savePlan} and
 * {@link RoutePlanDao#replaceStops} write the plan and its stops in one transaction, so a half-saved plan
 * cannot exist - not after a crash, not after a rotation, not after the process is killed mid-write. The
 * order IS the plan, and a plan with the wrong number of stops in it is not a plan with a small error.
 */
public class PlanRepository {

    private static final String TAG = "AlphaRoutePlanRepo";

    /**
     * The longest name accepted.
     *
     * <p>Not a database limit - the column is a string. It is a screen limit: a plan name is shown in a
     * button and in a menu row, and a name that wraps or is cut off cannot be chosen confidently.
     */
    private static final int MAX_NAME_LENGTH = 40;

    private final RoutePlanDao planDao;
    private final AppExecutors executors;

    public PlanRepository(@NonNull RoutePlanDao planDao, @NonNull AppExecutors executors) {
        this.planDao = planDao;
        this.executors = executors;
    }

    // ------------------------------------------------------------------ reading

    /**
     * Every saved plan, newest first.
     *
     * <p>Observed rather than read once, because a list of plans is exactly the sort of thing a screen
     * wants to redraw itself for: saving, renaming or deleting any of them changes this.
     */
    @NonNull
    public LiveData<List<RoutePlanEntity>> observePlans() {
        return planDao.observePlans();
    }

    /**
     * The plans made for a round, newest first, read once.
     *
     * <p>Used where the caller has to act on the list - pick one, merge it with what is pending, then write
     * it back. That work must not have the list change underneath it halfway through.
     */
    public void findPlansInRoundNow(int roundNumber,
                                    @NonNull RepositoryCallback<List<RoutePlanEntity>> callback) {
        executors.diskIO().execute(() -> {
            List<RoutePlanEntity> plans;
            try {
                plans = planDao.findPlansInRoundNow(roundNumber);
            } catch (RuntimeException e) {
                Log.e(TAG, "Could not read the plans for round " + roundNumber, e);
                plans = null;
            }
            final List<RoutePlanEntity> result = plans;
            executors.postToMain(() -> callback.onResult(result));
        });
    }

    /**
     * One plan's stops, in driving order, read once.
     *
     * <p>A {@code null} result means the read failed or the plan is gone; an empty list is a real answer
     * meaning "this plan has no stops", which a caller can tell apart.
     */
    public void findStopsNow(long planId,
                             @NonNull RepositoryCallback<List<RoutePlanStopEntity>> callback) {
        executors.diskIO().execute(() -> {
            List<RoutePlanStopEntity> stops;
            try {
                stops = planDao.findStops(planId);
            } catch (RuntimeException e) {
                Log.e(TAG, "Could not read the stops of plan " + planId, e);
                stops = null;
            }
            final List<RoutePlanStopEntity> result = stops;
            executors.postToMain(() -> callback.onResult(result));
        });
    }

    // ------------------------------------------------------------------ writing

    /**
     * Saves a new plan.
     *
     * <p><b>The default name comes from here, not from the screen.</b> "Plan 1", "Plan 2" and so on are
     * generated by counting the plans already in the round, so two plans cannot end up with the same
     * default name however fast the user taps.
     *
     * <p><b>The saved row comes back, not just its id</b>, because the name is generated here - the caller
     * has no other way to learn what the plan ended up being called, and showing the user a plan they
     * cannot name would be a strange thing to do.
     *
     * @param order  the order the user decided. Its stops are stored by store id and position
     * @param result receives the saved plan, or {@code null} when the write failed
     */
    public void createPlan(int roundNumber,
                           @Nullable String name,
                           @NonNull OptimizationPlan order,
                           @NonNull RepositoryCallback<RoutePlanEntity> result) {

        executors.diskIO().execute(() -> {
            RoutePlanEntity saved = null;
            try {
                RoutePlanEntity plan = new RoutePlanEntity();
                plan.name = defaultName(roundNumber, name);
                plan.roundNumber = roundNumber;
                plan.createdAt = System.currentTimeMillis();
                plan.totalDistanceMetres = order.totalDistanceMetres();
                plan.totalDurationSeconds = order.totalDurationSeconds();
                plan.startedAtLocation = order.startsAtCurrentLocation();
                plan.endedAtHome = order.endsAtHome();

                long planId = planDao.savePlan(plan, stopsFrom(order));

                // savePlan fills in the id on the row it was given, so the caller gets back exactly what
                // was written rather than a second read that could disagree with it.
                plan.id = planId;
                saved = plan;
            } catch (RuntimeException e) {
                Log.e(TAG, "Could not save a new route plan", e);
            }
            final RoutePlanEntity written = saved;
            executors.postToMain(() -> result.onResult(written));
        });
    }

    /**
     * Replaces the order of an existing plan.
     *
     * <p>Delete-then-insert inside one transaction - see {@link RoutePlanDao#replaceStops}. The plan's own
     * name and creation time are untouched; only the order and the totals move.
     */
    public void replacePlanStops(long planId,
                                 @NonNull OptimizationPlan order,
                                 @NonNull RepositoryCallback<WriteOutcome> result) {

        executors.diskIO().execute(() -> {
            WriteOutcome outcome;
            try {
                planDao.replaceStops(planId, stopsFrom(order));
                int updated = planDao.updatePlanSummary(
                        planId,
                        order.totalDistanceMetres(),
                        order.totalDurationSeconds(),
                        order.startsAtCurrentLocation(),
                        order.endsAtHome());
                // No row updated means the plan was deleted between the screen loading it and this write -
                // an ordinary race, not a bug, and the screen needs to know so it can stop pretending.
                outcome = updated == 1 ? WriteOutcome.SUCCESS : WriteOutcome.NOT_FOUND;
            } catch (RuntimeException e) {
                Log.e(TAG, "Could not replace the stops of plan " + planId, e);
                outcome = WriteOutcome.FAILED;
            }
            final WriteOutcome finalOutcome = outcome;
            executors.postToMain(() -> result.onResult(finalOutcome));
        });
    }

    /** Renames a plan. A blank or over-long name is refused rather than stored. */
    public void renamePlan(long planId,
                           @Nullable String name,
                           @NonNull RepositoryCallback<WriteOutcome> result) {

        String cleaned = name == null ? "" : name.trim();
        if (cleaned.isEmpty() || cleaned.length() > MAX_NAME_LENGTH) {
            executors.postToMain(() -> result.onResult(WriteOutcome.INVALID_DATA));
            return;
        }

        executors.diskIO().execute(() -> {
            WriteOutcome outcome;
            try {
                outcome = planDao.renamePlan(planId, cleaned) == 1
                        ? WriteOutcome.SUCCESS
                        : WriteOutcome.NOT_FOUND;
            } catch (RuntimeException e) {
                Log.e(TAG, "Could not rename plan " + planId, e);
                outcome = WriteOutcome.FAILED;
            }
            final WriteOutcome finalOutcome = outcome;
            executors.postToMain(() -> result.onResult(finalOutcome));
        });
    }

    /**
     * Deletes a plan.
     *
     * <p>Its stops go with it through the foreign key's {@code CASCADE}, so there is no second delete to
     * remember and no way for orphan rows to accumulate.
     */
    public void deletePlan(long planId, @NonNull RepositoryCallback<WriteOutcome> result) {
        executors.diskIO().execute(() -> {
            WriteOutcome outcome;
            try {
                planDao.deletePlanOrThrow(planId);
                outcome = WriteOutcome.SUCCESS;
            } catch (IllegalStateException e) {
                // The row was already gone. From the user's side the plan is deleted either way, so this is
                // not worth an error message.
                Log.w(TAG, "Plan " + planId + " was already deleted");
                outcome = WriteOutcome.NOT_FOUND;
            } catch (RuntimeException e) {
                Log.e(TAG, "Could not delete plan " + planId, e);
                outcome = WriteOutcome.FAILED;
            }
            final WriteOutcome finalOutcome = outcome;
            executors.postToMain(() -> result.onResult(finalOutcome));
        });
    }

    // ------------------------------------------------------------------ helpers

    /**
     * Turns a decided order into rows.
     *
     * <p><b>The position is the index, 1-based</b>, taken from the plan's own sequence rather than from the
     * loop counter - so if the two ever disagreed, the plan would store the order the screen actually shows.
     * The leg figures come along because a plan reopened tomorrow should still be able to say how long each
     * hop was.
     */
    @NonNull
    private static List<RoutePlanStopEntity> stopsFrom(@NonNull OptimizationPlan order) {
        List<RoutePlanStopEntity> stops = new ArrayList<>(order.stopCount());
        for (OptimizationStop stop : order.stops()) {
            RoutePlanStopEntity row = new RoutePlanStopEntity();
            row.storeId = stop.storeId();
            row.position = stop.sequence();
            row.legDistanceMetres = stop.legDistanceMetres();
            row.legDurationSeconds = stop.legDurationSeconds();
            stops.add(row);
        }
        return stops;
    }

    /**
     * The name to save under: the one given, or the next free default.
     *
     * <p>Called on the disk thread, because it reads the database. That is deliberate - generating the name
     * needs to know how many plans the round already has, and counting on the main thread would be a
     * database read in a place that must never do one.
     */
    @NonNull
    private String defaultName(int roundNumber, @Nullable String requested) {
        if (requested != null && !requested.trim().isEmpty()) {
            String trimmed = requested.trim();
            return trimmed.length() > MAX_NAME_LENGTH ? trimmed.substring(0, MAX_NAME_LENGTH) : trimmed;
        }
        return "Plan " + (planDao.countPlansInRound(roundNumber) + 1);
    }
}
