package com.cph.alpharoute.domain;

import androidx.annotation.NonNull;

import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * What a cloud restore would actually do, worked out before anything is written.
 *
 * <p><b>Why this is a class rather than a couple of counters in the screen.</b> The whole point of a manual
 * sync is that the user decides with the numbers in front of them. A preview that says "2 stores will be
 * added" and then adds four is worse than no preview at all - it teaches the user that the confirmation
 * dialog is decoration. So this mirrors the merge rule in {@code BackupTransactionDao.importAll} exactly,
 * and {@code CloudSyncSummaryTest} pins the two together.
 *
 * <p><b>The rule being mirrored, in one place:</b>
 *
 * <ul>
 *   <li>A cloud store is <b>already here</b> when its <i>store code</i> exists locally. The app's copy
 *       wins - it may have been edited, completed or moved since the cloud copy was written, and
 *       overwriting it would silently undo that.</li>
 *   <li>A cloud completion is <b>already here</b> when that store already has a completion in that
 *       <i>round</i>. The unique index on {@code (storeId, roundNumber)} makes a second one impossible
 *       anyway; counting it first means the user is told rather than shown an error.</li>
 *   <li>A completion whose store resolves to nothing is <b>unresolved</b>. The validator refuses a document
 *       like that, so a non-zero count here means the two steps disagree - which is worth surfacing rather
 *       than hiding.</li>
 * </ul>
 *
 * <p><b>Ids are never compared, and that is deliberate.</b> Row ids are auto-generated by SQLite, so store
 * 7 in the cloud is not store 7 on this phone. {@code storeCode} is the app's own stable identity, and it
 * is what both sides are matched on.
 *
 * <p>Pure Java (AD-11), so every branch above is provable on a laptop.
 */
public final class CloudSyncSummary {

    /**
     * One completion, identified the way the database identifies it: by store and by round.
     *
     * <p>Two completions of the same store in the same round are the same completion, whatever their
     * timestamps say - that is what the unique index means.
     */
    public static final class CompletionKey {

        private final String storeCode;
        private final int roundNumber;

        public CompletionKey(@NonNull String storeCode, int roundNumber) {
            this.storeCode = storeCode;
            this.roundNumber = roundNumber;
        }

        @NonNull
        public String storeCode() {
            return storeCode;
        }

        public int roundNumber() {
            return roundNumber;
        }

        @Override
        public boolean equals(Object other) {
            if (this == other) {
                return true;
            }
            if (!(other instanceof CompletionKey)) {
                return false;
            }
            CompletionKey that = (CompletionKey) other;
            return roundNumber == that.roundNumber && storeCode.equals(that.storeCode);
        }

        @Override
        public int hashCode() {
            return storeCode.hashCode() * 31 + roundNumber;
        }

        @NonNull
        @Override
        public String toString() {
            return storeCode + "@" + roundNumber;
        }
    }

    private final int cloudStoreCount;
    private final int cloudCompletionCount;
    private final int storesNew;
    private final int storesAlreadyHere;
    private final int completionsNew;
    private final int completionsAlreadyHere;
    private final int completionsUnresolved;

    private CloudSyncSummary(int cloudStoreCount,
                             int cloudCompletionCount,
                             int storesNew,
                             int storesAlreadyHere,
                             int completionsNew,
                             int completionsAlreadyHere,
                             int completionsUnresolved) {
        this.cloudStoreCount = cloudStoreCount;
        this.cloudCompletionCount = cloudCompletionCount;
        this.storesNew = storesNew;
        this.storesAlreadyHere = storesAlreadyHere;
        this.completionsNew = completionsNew;
        this.completionsAlreadyHere = completionsAlreadyHere;
        this.completionsUnresolved = completionsUnresolved;
    }

    /**
     * Works out what a merge would add.
     *
     * @param cloudStoreCodes  every store code in the cloud document
     * @param cloudCompletions every completion in it
     * @param localStoreCodes  every store code already on this phone
     * @param localCompletions every completion already on this phone
     */
    @NonNull
    public static CloudSyncSummary of(@NonNull List<String> cloudStoreCodes,
                                      @NonNull List<CompletionKey> cloudCompletions,
                                      @NonNull Set<String> localStoreCodes,
                                      @NonNull Set<CompletionKey> localCompletions) {

        // Codes that a completion can be attached to: the ones already here, plus the ones this merge would
        // bring in. A completion pointing at a store that is in neither is the unresolved case.
        Set<String> resolvableCodes = new HashSet<>(localStoreCodes);
        Set<String> countedCodes = new HashSet<>();

        int storesNew = 0;
        int storesAlreadyHere = 0;
        for (String code : cloudStoreCodes) {
            if (!countedCodes.add(code)) {
                // The stores table has a unique storeCode, so a well-formed document cannot do this.
                // Counting it twice would inflate the preview.
                continue;
            }
            if (localStoreCodes.contains(code)) {
                storesAlreadyHere++;
            } else {
                storesNew++;
                resolvableCodes.add(code);
            }
        }

        int completionsNew = 0;
        int completionsAlreadyHere = 0;
        int completionsUnresolved = 0;
        Set<CompletionKey> countedCompletions = new HashSet<>();

        for (CompletionKey key : cloudCompletions) {
            if (!resolvableCodes.contains(key.storeCode())) {
                completionsUnresolved++;
                continue;
            }
            // A repeat inside the document itself. The transaction skips it for the same reason: the store
            // already has a completion in that round by the time the second one is read.
            if (!countedCompletions.add(key)) {
                completionsAlreadyHere++;
                continue;
            }
            if (localCompletions.contains(key)) {
                completionsAlreadyHere++;
            } else {
                completionsNew++;
            }
        }

        return new CloudSyncSummary(
                countedCodes.size(),
                cloudCompletions.size(),
                storesNew,
                storesAlreadyHere,
                completionsNew,
                completionsAlreadyHere,
                completionsUnresolved);
    }

    /** How many stores the cloud document holds. */
    public int cloudStoreCount() {
        return cloudStoreCount;
    }

    /** How many completions the cloud document holds. */
    public int cloudCompletionCount() {
        return cloudCompletionCount;
    }

    /** How many stores a merge would add. */
    public int storesNew() {
        return storesNew;
    }

    /** How many the phone already has, and would keep its own copy of. */
    public int storesAlreadyHere() {
        return storesAlreadyHere;
    }

    /** How many completions a merge would add. */
    public int completionsNew() {
        return completionsNew;
    }

    /** How many the phone already has. */
    public int completionsAlreadyHere() {
        return completionsAlreadyHere;
    }

    /**
     * How many completions name a store that is in neither the cloud document nor this phone.
     *
     * <p>Should always be zero - the validator refuses a document like that. A non-zero value means the
     * validator and the transaction disagree, and the screen says so rather than quietly dropping records.
     */
    public int completionsUnresolved() {
        return completionsUnresolved;
    }

    /**
     * Whether a merge would leave the phone exactly as it is.
     *
     * <p>Worth knowing before the user taps: "nothing new" is a real answer, and it is much better than a
     * silent success that changed nothing and looks like a failure.
     */
    public boolean nothingNew() {
        return storesNew == 0 && completionsNew == 0;
    }
}
